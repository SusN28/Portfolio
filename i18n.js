function setLanguage(language) {
  const selectedTranslations = translations[language];
  if (!selectedTranslations) return;

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(selectedTranslations, key)) {
      element.textContent = selectedTranslations[key];
    }
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    const key = element.dataset.i18nAlt;
    if (Object.prototype.hasOwnProperty.call(selectedTranslations, key)) {
      element.alt = selectedTranslations[key];
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    const key = element.dataset.i18nAria;
    if (Object.prototype.hasOwnProperty.call(selectedTranslations, key)) {
      element.setAttribute('aria-label', selectedTranslations[key]);
    }
  });

  document.documentElement.lang = language;
  localStorage.setItem('language', language);

  document.querySelectorAll('[data-lang]').forEach(button => {
    button.classList.toggle('active', button.dataset.lang === language);
    button.setAttribute('aria-pressed', button.dataset.lang === language ? 'true' : 'false');
  });
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-lang]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });

  setLanguage(localStorage.getItem('language') || 'de');
});